  @Override
  public Identifier toPhysicalTableName(Identifier name, JdbcEnvironment jdbcEnvironment) {
    return translate(super.toPhysicalTableName(name, jdbcEnvironment));
  }

  @Override
  public Identifier toPhysicalSequenceName(Identifier name, JdbcEnvironment jdbcEnvironment) {
    return translate(super.toPhysicalSequenceName(name, jdbcEnvironment));
  }

  @Override
  public Identifier toPhysicalColumnName(Identifier name, JdbcEnvironment jdbcEnvironment) {
    return translate(super.toPhysicalColumnName(name, jdbcEnvironment));
  }

  private Identifier translate(Identifier identifier) {
    if (identifier == null) return null;
    String translated = NAMES.getOrDefault(identifier.getText(), identifier.getText());
    return Identifier.toIdentifier(translated, identifier.isQuoted());
  }
